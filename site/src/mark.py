# Generates site/public/brand/swarmaa-mark.svg: a faceted doner spit that really rotates (pure SVG/SMIL,
# so it animates even as an <img>), with agent bees riding two orbit rings that pass behind and in front.
#   python3 site/src/mark.py && python3 site/src/mark.py dark   (dark: light lines, for ink backgrounds)
from math import cos, sin, pi
from pathlib import Path

import sys
DARK = 'dark' in sys.argv[1:]
INK, FLAME = ('#F4EFE6' if DARK else '#15111F'), '#FF5A3C'
N, K, STEP = 12, 12, 0.5            # facets, frames per facet step, seconds per facet step (full turn = N*STEP)
CX, YT, YB, RT, RB = 100, 52, 150, 50, 22
TILT = 0.2                          # ellipse squash: we look slightly down on the cone

def mix(a, b, t):
    pa, pb = [int(a[i:i+2], 16) for i in (1, 3, 5)], [int(b[i:i+2], 16) for i in (1, 3, 5)]
    return '#' + ''.join(f'{round(x + (y - x) * t):02X}' for x, y in zip(pa, pb))

def shade(mid, i):
    l = cos(mid + 0.6)                                  # light from front-left
    c = mix(FLAME, '#FF8F73', l) if l > 0 else mix(FLAME, '#A8200B', -l)
    return mix(c, '#7A1606', .38) if i % 2 else c        # every other facet seared: the stripes show the turn

def pt(r, y, a):
    return f'{CX + r * sin(a):.2f} {y + r * TILT * cos(a):.2f}'

def facet(i, phase):
    a0 = i * 2 * pi / N + phase; a1 = a0 + 2 * pi / N; mid = (a0 + a1) / 2
    if cos(mid) <= 0:                                   # facing away: collapse onto the silhouette edge
        a0 = a1 = pi / 2 if sin(mid) > 0 else -pi / 2
    return f'M{pt(RT, YT, a0)} L{pt(RT, YT, a1)} L{pt(RB, YB, a1)} L{pt(RB, YB, a0)}Z', shade(mid, i)

frames = [[facet(i, f / K * 2 * pi / N) for f in range(2 * K + 1)] for i in range(N)]
dur = f'{2 * STEP}s'
facets = '\n'.join(
    f'    <path d="{fr[0][0]}" fill="{fr[0][1]}"><animate attributeName="d" values="{";".join(p for p, _ in fr)}" dur="{dur}" repeatCount="indefinite"/>'
    f'<animate attributeName="fill" values="{";".join(c for _, c in fr)}" dur="{dur}" repeatCount="indefinite"/></path>'
    for fr in frames)

def r_at(y): return RT + (RB - RT) * (y - YT) / (YB - YT)
grooves = ''.join(f'<path d="M{CX - r_at(y):.1f} {y} A{r_at(y):.1f} {r_at(y) * TILT:.1f} 0 0 0 {CX + r_at(y):.1f} {y}"/>' for y in (78, 102, 126))

# Orbits: (center y, rx, ry, tilt deg, seconds, [(color, phase 0..1)])
ORBITS = [(84, 88, 17, -12, 3.6, [('#D4FF3A', 0), ('#FFE08A', .36), ('#9CC8FF', .7)]),
          (128, 76, 14, 9, 3.0, [('#D6C2FF', .15), ('#FFB8D9', .62)])]

def orbit(layer):
    out = []
    for cy, rx, ry, deg, sec, bees in ORBITS:
        back = layer == 'back'
        sweep = '1' if back else '0'                    # top arc = behind the cone, bottom arc = in front
        g = [f'<g transform="rotate({deg} {CX} {cy})">',
             f'<path d="M{CX - rx} {cy} A{rx} {ry} 0 0 {sweep} {CX + rx} {cy}" fill="none" stroke="{INK}" stroke-width="2.4" stroke-linecap="round" stroke-dasharray="0.1 7" stroke-opacity="{.35 if back else .7}"/>']
        path = f'M{CX - rx} {cy} A{rx} {ry} 0 0 1 {CX + rx} {cy} A{rx} {ry} 0 0 1 {CX - rx} {cy}'
        for color, ph in bees:
            begin = f'-{ph * sec:.2f}s'
            flip = '' if back else ' transform="scale(-1 1)"'
            g.append(f'<use href="#bee" x="-14" y="-11" color="{color}"{flip}>'
                     f'<animateMotion path="{path}" dur="{sec}s" begin="{begin}" repeatCount="indefinite"/>'
                     f'<animate attributeName="opacity" values="{"1;0" if back else "0;1"}" keyTimes="0;.5" calcMode="discrete" dur="{sec}s" begin="{begin}" repeatCount="indefinite"/></use>')
        out.append(''.join(g) + '</g>')
    return '\n  '.join(out)

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200" role="img" aria-label="Swarmaa">
  <!-- generated by site/src/mark.py -->
  <defs>
    <symbol id="bee" viewBox="-10 -12 20 20" width="28" height="28" overflow="visible">
      <g fill="#FFFFFF" stroke="{INK}" stroke-width="1.6">
        <ellipse cx="-2.5" cy="-5.5" rx="3" ry="4.5"><animate attributeName="ry" values="4.5;1;4.5" dur=".12s" repeatCount="indefinite"/></ellipse>
        <ellipse cx="2" cy="-5.5" rx="3" ry="4.5"><animate attributeName="ry" values="1;4.5;1" dur=".12s" repeatCount="indefinite"/></ellipse>
      </g>
      <ellipse rx="6.5" ry="4.8" fill="currentColor" stroke="{INK}" stroke-width="2"/>
      <path d="M-.5 -4.4v8.8" stroke="{INK}" stroke-width="2.2"/>
    </symbol>
  </defs>
  {orbit('back')}
  <path d="M{CX} 6 L{CX + 4.5} 20 V176 L{CX} 192 L{CX - 4.5} 176 V20 Z" fill="{INK}"/>
  <g>
{facets}
  </g>
  <g fill="none" stroke="{INK}" stroke-width="2" stroke-opacity=".28">{grooves}</g>
  <ellipse cx="{CX}" cy="{YT}" rx="{RT}" ry="{RT * TILT}" fill="#FFB49E"/>
  <ellipse cx="{CX}" cy="{YT}" rx="{RT * .62}" ry="{RT * TILT * .62}" fill="none" stroke="#F0361A" stroke-opacity=".55" stroke-width="2.5"/>
  <circle cx="{CX}" cy="{YT}" r="3.5" fill="{INK}"/>
  <path d="M{CX - RT} {YT} L{CX - RB} {YB} A{RB} {RB * TILT} 0 0 0 {CX + RB} {YB} L{CX + RT} {YT} A{RT} {RT * TILT} 0 0 0 {CX - RT} {YT} A{RT} {RT * TILT} 0 0 1 {CX + RT} {YT}" fill="none" stroke="{INK}" stroke-width="5" stroke-linejoin="round"/>
  {orbit('front')}
</svg>
'''
Path(__file__).resolve().parents[1].joinpath(f"public/brand/swarmaa-mark{'-dark' if DARK else ''}.svg").write_text(svg)
