import { randomUUID } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { parseArgs } from 'node:util';
import { serviceUrl } from '../src/bridge/config.js';

const { values } = parseArgs({ options: {
  url: { type: 'string', default: process.env.PUBLIC_URL ?? 'http://127.0.0.1:8787' },
  scope: { type: 'string', default: 'project:demo' },
  'dot-token-file': { type: 'string', default: '.local/dot.json' },
  'grok-token-file': { type: 'string', default: '.local/grok.json' },
  'worker-token-file': { type: 'string', default: '.local/demo-worker.json' },
} });
const origin = serviceUrl(values.url);
async function credential(path: string): Promise<string> {
  const value = JSON.parse(await readFile(path, 'utf8')) as { token?: unknown };
  if (typeof value.token !== 'string' || !/^cn_[A-Za-z0-9_-]{43}$/.test(value.token)) throw new Error('Credential file does not contain a provisioned token.');
  return value.token;
}
const [dot, grok, worker] = await Promise.all([
  credential(values['dot-token-file']!), credential(values['grok-token-file']!), credential(values['worker-token-file']!),
]);
async function call<T>(token: string, name: string, args: unknown): Promise<T> {
  const response = await fetch(`${origin}/api/tools/${name}`, { method: 'POST', redirect: 'error', signal: AbortSignal.timeout(15000), headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify(args) });
  if (!response.ok) throw new Error(`Demo ${name} failed with HTTP ${response.status}. Inspect the service log without exposing credentials.`);
  const body = await response.json() as { result: T };
  return body.result;
}
const key = `demo-${randomUUID()}`;
const memory = await call<{ memory: { id: string } }>(dot, 'memory_propose', {
  scope: values.scope, kind: 'note', key, content: 'Demonstration: both entrypoints can access this shared project record.',
  source: { type: 'tool', reference: 'scripts/demo.ts: explicitly generated demonstration data' },
});
await call(grok, 'memory_get', { memory_id: memory.memory.id });
const task = await call<{ task: { id: string } }>(dot, 'task_submit', {
  scope: values.scope, kind: 'research', objective: 'Demonstrate a durable handoff without invoking a model or executing project commands.',
  idempotency_key: key, required_capability: 'demo.read', context_refs: [memory.memory.id],
  constraints: ['Use demonstration data only.'], acceptance_criteria: ['The second entrypoint can read the completed task.'],
});
await call(grok, 'task_get', { task_id: task.task.id });
const claim = await call<{ task: { id: string } | null; lease_token: string; lease_generation: number }>(worker, 'task_claim', { scope: values.scope, capabilities: ['demo.read'], lease_seconds: 120 });
if (claim.task?.id !== task.task.id) throw new Error('Demo worker did not receive its unique demonstration task.');
const lease = { task_id: task.task.id, lease_token: claim.lease_token, lease_generation: claim.lease_generation };
const artifact = await call<{ artifact: { id: string } }>(worker, 'artifact_put', { ...lease, name: 'demo-result.txt', content: 'This artifact was generated by the local demonstration script; no AI provider was invoked.', media_type: 'text/plain' });
await call(worker, 'task_finish', { ...lease, outcome: 'completed', result: { demonstration: true, provider_invoked: false }, artifact_ids: [artifact.artifact.id] });
const final = await call<{ task: { status: string } }>(grok, 'task_get', { task_id: task.task.id });
if (final.task.status !== 'completed') throw new Error('The final task state was not completed.');
process.stdout.write(`${JSON.stringify({ demo: 'service-flow', scope: values.scope, memory_id: memory.memory.id, task_id: task.task.id, artifact_id: artifact.artifact.id, task_status: final.task.status, provider_integration_verified: false }, null, 2)}\n`);
